"""eval/score_mentoring.py — GROW-note benchmark on the mentoring sessions (eval/results/mentoring_eval.jsonl).

Per session and pooled:
  processing   seconds of computing per minute of audio (real-time factor) and per stage
  speakers     sessions in which pyannote found exactly two speakers; roles assigned as one mentor and one mentee
  GROW         sessions with all four sections filled (goal, reality, options, way forward), and per-section rates
  grounding    sentences per note, citation coverage, supported / partly / unsupported (pipeline judge, Wilson 95% CI)
  repair       sentences flagged, rewritten and removed by sentence repair; notes regenerated by the cascade
  recheck      the same final sentences judged again by a held-out judge (recheck_<judge>_mentoring.jsonl), if present
Writes eval/results/mentoring_scores.json.
"""
import json
import math
from collections import Counter, defaultdict
from pathlib import Path

import os
ROOT = Path(__file__).resolve().parent / "results"
TAG = os.environ.get("MENTORING_TAG", "")


def load(name):
    p = ROOT / name
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []


def wilson(k, n, z=1.96):
    if n == 0:
        return None
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    r = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return [round((c - r) / d, 4), round((c + r) / d, 4)]


def rate(k, n):
    return {"k": k, "n": n, "rate": round(k / n, 4) if n else None, "ci95": wilson(k, n)}


def median(xs):
    xs = sorted(xs)
    return xs[len(xs) // 2] if xs else None


rows = load(f"mentoring_eval{TAG}.jsonl")
out = {"sessions": len(rows)}
if rows:
    mins = sum(r["durationSec"] for r in rows) / 60
    out["audio_minutes"] = round(mins, 1)
    out["mentees"] = sorted({r["mentee"] for r in rows})
    out["sessions_per_mentee"] = dict(Counter(r["mentee"] for r in rows))

    total_s = [sum(r["seconds"].values()) for r in rows]
    out["processing"] = {
        "seconds_per_audio_minute_median": round(median([t / (r["durationSec"] / 60) for t, r in zip(total_s, rows)]), 1),
        "stage_seconds_median": {k: round(median([r["seconds"][k] for r in rows]), 1) for k in rows[0]["seconds"]},
    }
    out["speakers"] = {
        "two_speakers_found": rate(sum(1 for r in rows if r["speakersFound"] == 2), len(rows)),
        "one_mentor_one_mentee": rate(sum(1 for r in rows if sorted(r["roleMap"].values()) == ["Mentee", "Mentor"]), len(rows)),
        "mentor_share_of_words_mean": round(sum(r["mentorShare"] for r in rows) / len(rows), 3),
        "diarization": dict(Counter((r["diarization"] or "none").split(" (")[0] for r in rows)),
        "attribution": dict(Counter(r["alignedBy"] or "none" for r in rows)),
        "stt": dict(Counter((r["stt"] or "none").split(" (")[0] for r in rows)),
    }
    sec = Counter(s for r in rows for s in r["growSections"])
    out["grow"] = {
        "all_four_sections": rate(sum(1 for r in rows if r["growFilled"] == 4), len(rows)),
        "section_filled": {k: rate(sec[k], len(rows)) for k in ("goal", "reality", "options", "way_forward")},
    }
    sent = sum(r["sentences"] or 0 for r in rows)
    out["grounding"] = {
        "sentences": sent,
        "sentences_per_note_mean": round(sent / len(rows), 1),
        "cited": rate(sum(r["cited"] or 0 for r in rows), sent),
        "supported": rate(sum(r["supported"] or 0 for r in rows), sent),
        "partial": rate(sum(r["partial"] or 0 for r in rows), sent),
        "unsupported": rate(sum(r["unsupported"] or 0 for r in rows), sent),
        "notes_with_unsupported": sum(1 for r in rows if (r["unsupported"] or 0) > 0),
        "judge_vendors": dict(Counter((r["verifier"] or "none").split(" (")[0] for r in rows)),
    }
    out["repair"] = {
        "flagged": sum((r.get("repair") or {}).get("flagged", 0) for r in rows),
        "rewritten": sum((r.get("repair") or {}).get("rewritten", 0) for r in rows),
        "removed": sum((r.get("repair") or {}).get("removed", 0) for r in rows),
        "cascade_escalations": sum(1 for r in rows if (r.get("cascade") or {}).get("escalated")),
    }
    by = defaultdict(list)
    for r in rows:
        by[r["mentee"]].append(r)
    out["per_mentee"] = {m: {"sessions": len(v), "grow_complete": sum(1 for r in v if r["growFilled"] == 4),
                             "supported": round(sum(r["supported"] or 0 for r in v) / max(sum(r["sentences"] or 0 for r in v), 1), 3)} for m, v in by.items()}

for judge in ("groq", "openrouter"):
    rc = load(f"recheck_{judge}_mentoring{TAG}.jsonl")
    if rc:
        total = sum(r["sentences"] for r in rc)
        agree = sum(1 for r in rc for x in r["labels"] if x["recheck"] == x["pipeline"])
        out[f"recheck_{judge}"] = {
            "notes": len(rc), "sentences": total,
            "supported": rate(sum(r["supported"] for r in rc), total),
            "unsupported": rate(sum(r["unsupported"] for r in rc), total),
            "agreement_with_pipeline": rate(agree, total),
            "judges": sorted({r["judge"] for r in rc}),
        }

(ROOT / f"mentoring_scores{TAG}.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
print(json.dumps(out, indent=1)[:3500])
